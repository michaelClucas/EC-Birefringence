"""Skeptic checks on the RESULT draft (task 20261120-020).

S1  Teleparallel (TEGR) FRW torsion: trace T_mu = 3 d ln a, axial S = 0 (sympy), and the beta a CFJ
    coupling xi T_mu A_nu Ftilde^{mu nu} would give. Same for a generic unsourced axial background
    S_0hat = eps H (Magueijo-Zlosnik type, size not derived).
S2  KK charge-to-mass: lightest state with KK charge e when the KK photon is the EM photon.
S3  Gauge-invariant torsion-photon operators above CFJ dimension (Das-Mohanty-Prasanna F dF~ T,
    (div S) F F~) evaluated on the spin-sourced EC torsion of EC-02: required cutoff.
S4  ACT + WMAP/Planck combination: Cosmoglobe alternative instead of EK22 for the bounded-model penalties.
All measured inputs come from data/ (CONVENTIONS.md units). Run from the repo root.
"""
import csv
import math
import os

import sympy as sp

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
NPASS = NFAIL = 0


def check(name, ok, msg=""):
    global NPASS, NFAIL
    NPASS += bool(ok)
    NFAIL += not ok
    print(f"[{'PASS' if ok else 'FAIL'}] {name} {msg}")


def rows(name):
    with open(os.path.join(ROOT, "data", name), newline="", encoding="utf-8") as f:
        return {r["id"]: r for r in csv.DictReader(f)}


cos = {k: r["value"] for k, r in rows("cosmo_inputs.csv").items()}
bir = rows("birefringence_measurements.csv")
num = lambda k: float(cos[k])
beta_deg = float(bir["DPK25-beta-baseline"]["value"])
beta = math.radians(beta_deg)
zstar = num("z_star")

# ---------------------------------------------------------------- S1 teleparallel / unsourced torsion
tau, x, y, z = sp.symbols("tau x y z")
X = [tau, x, y, z]
a = sp.Function("a")(tau)
e = sp.diag(a, a, a, a)  # e^A_mu, diagonal FRW tetrad, conformal time
einv = e.inv()  # e_A^mu (row mu, column A after transpose handled below)
# Weitzenboeck connection Gamma^l_{mu nu} = e_A^l d_mu e^A_nu (derivative index first, CONVENTIONS.md)
G = [[[sp.simplify(sum(einv[l, A] * sp.diff(e[A, n], X[m]) for A in range(4))) for n in range(4)]
      for m in range(4)] for l in range(4)]
T = [[[sp.simplify(G[l][m][n] - G[l][n][m]) for n in range(4)] for m in range(4)] for l in range(4)]
Ttrace = [sp.simplify(sum(T[l][m][l] for l in range(4))) for m in range(4)]
check("S1a TEGR FRW trace torsion T_tau = 3 a'/a", sp.simplify(Ttrace[0] - 3 * sp.diff(a, tau) / a) == 0,
      f"(T_mu = {Ttrace})")
g = sp.diag(-a**2, a**2, a**2, a**2)
Tlow = [[[sp.simplify(sum(g[l, k] * T[k][m][n] for k in range(4))) for n in range(4)] for m in range(4)]
        for l in range(4)]
eps = sp.LeviCivita
S_axial = [sp.simplify(sum(eps(mu, n, r, s) * Tlow[n][r][s] for n in range(4) for r in range(4)
                           for s in range(4))) for mu in range(4)]
check("S1b TEGR FRW axial torsion vanishes (diagonal tetrad)", all(s == 0 for s in S_axial))
check("S1c T_mu is a gradient (closed), so CFJ with p = xi T is gauge invariant up to a total derivative",
      all(sp.simplify(sp.diff(Ttrace[m], X[n]) - sp.diff(Ttrace[n], X[m])) == 0 for m in range(4) for n in range(4)))
# beta = 1/2 int p_tau dtau = (3 xi/2) ln(1+z*)  (CONVENTIONS.md: beta = +1/2 int p_tau dtau)
xi_TEGR = 2 * beta / (3 * math.log(1 + zstar))
print(f"  S1d TEGR + CFJ(xi T): beta = (3 xi/2) ln(1+z*) = {1.5*math.log(1+zstar):.2f} xi rad;"
      f" beta = {beta_deg} deg needs xi = {xi_TEGR:.2e} (achromatic, no spin source)")
# generic unsourced axial background S_0hat = eps H(t): beta = (xi/2) int S dt = (xi eps / 2) ln(1+z*)
xieps = 2 * beta / math.log(1 + zstar)
H0 = num("H0") / (num("Mpc_km")) * num("hbar_eV_s")
print(f"  S1e unsourced axial torsion S_0hat = eps H: needs xi*eps = {xieps:.2e};"
      f" S_0hat today = eps*{H0:.2e} eV vs lab |S_0| < 7.3e-22 eV (does not bind)")
check("S1f unsourced O(H) torsion needs only xi*eps ~ 1e-3 (not 28 orders)", xieps < 1e-2)

# ---------------------------------------------------------------- S2 KK charge-to-mass
alpha, me, MP = num("alpha_em"), num("m_e_eV"), num("MP_reduced_eV")
e_charge = math.sqrt(4 * math.pi * alpha)
# e^4 = dy + k A, k = sqrt(2 kappa_4) (016 Sec. 1): mode e^{i n y/R} has q_n = n k / R, mass >= |n|/R
qm_max = math.sqrt(2) / MP
m_min = e_charge / qm_max
print(f"  S2 KK mode charge/mass <= sqrt(2)/M_P; charge e needs m >= e M_P/sqrt2 = {m_min:.2e} eV"
      f" = {m_min/me:.1e} m_e")
check("S2 no light (m << M_P) state carries KK charge e", m_min / me > 1e20)

# ---------------------------------------------------------------- S3 higher-dimension gauge-invariant ops
xi_needed_EC02 = 2.9e28  # regenerated by src.reproduce (EC-02 row), quoted here only to scale
H_star = None
# H at last scattering in eV (matter + radiation, Planck 2018 inputs)
h = num("H0") / 100
Om = num("Omega_m")
Tcmb = num("T_cmb_K")
Or = 2.469e-5 / h**2 * (Tcmb / 2.7255) ** 4 * (1 + 0.2271 * num("N_eff_SM"))  # standard photon+nu fraction
H_star = H0 * math.sqrt(Om * (1 + zstar) ** 3 + Or * (1 + zstar) ** 4)
# Operators (div S) F F~ / Lambda^2 and S.T F F~/Lambda^2 trade xi for (H/Lambda)^2 at best;
# Das-Mohanty-Prasanna xi1 T F dF~ trades xi for xi1 p^2 (p = photon energy, ~1 eV at z*).
p_star = 2.7 * num("k_B_eV_K") * Tcmb * (1 + zstar)
Lam_dim6 = H_star / math.sqrt(xi_needed_EC02)
Lam_DMP = p_star / math.sqrt(xi_needed_EC02)
print(f"  S3 with EC spin-sourced torsion (EC-02 needs xi = {xi_needed_EC02:.1e}):"
      f" (div S)FF~/L^2 needs L <~ H* /sqrt(xi) = {Lam_dim6:.1e} eV (H* = {H_star:.1e} eV);"
      f" DMP p^2 T coupling needs L <~ {Lam_DMP:.1e} eV")
check("S3 gauge-invariant higher-dimension ops with EC spin torsion need sub-eV^-? absurd cutoffs",
      Lam_dim6 < 1e-30 and Lam_DMP < 1e-10)

# ---------------------------------------------------------------- S4 combination choice
def comb(rid):
    r = bir[rid]
    return float(r["value"]), float(r["err_plus"])


for rid in ("DPK25-comb-EK22", "DPK25-comb-CG"):
    b, s = comb(rid)
    pk = (b - 0.2091) ** 2 / s**2 if b > 0.2091 else 0.0
    pe = (b - 0.09978) ** 2 / s**2
    print(f"  S4 {rid}: beta = {b} +- {s}; KK-02 k=1 penalty = {pk:.2f}; EC-03' 2.7% penalty = {pe:.2f}")
print(f"== {NPASS} PASS, {NFAIL} FAIL ==")
